def train_target(target_cfg, train_df, val_df, test_df):
    name = target_cfg["name"]
    print(f"\n{'='*72}")
    print(f"  TRAINING: {name}  |  target = |{target_cfg['move_col']}| >= {target_cfg['threshold']}")
    print(f"{'='*72}")

    X_train, _ = _to_float_array(train_df.select(ALL_FEATURES))
    y_train = train_df[f"target_{name}"].to_numpy().astype(int)
    X_val, _ = _to_float_array(val_df.select(ALL_FEATURES))
    y_val = val_df[f"target_{name}"].to_numpy().astype(int)
    X_test, _ = _to_float_array(test_df.select(ALL_FEATURES))
    y_test = test_df[f"target_{name}"].to_numpy().astype(int)

    print(f"  pos rates: train={y_train.mean():.4%}  val={y_val.mean():.4%}  test={y_test.mean():.4%}")
    print(f"  positives: train={y_train.sum():,}  val={y_val.sum():,}  test={y_test.sum():,}")

    # NOTE: scale_pos_weight intentionally NOT used.  With severe imbalance
    # (1% positives) it produces extreme predictions whose val log-loss is
    # worst at iter 1, killing early stopping.  Instead we leave the model
    # to learn natural probabilities and tune the threshold downstream.
    # Optimization metric set to AUC since it is invariant to base rate.
    model = lgb.LGBMClassifier(
        objective="binary",
        metric="auc",
        num_leaves=63,
        min_child_samples=200,
        learning_rate=0.05,
        n_estimators=1500,
        subsample=0.8,
        colsample_bytree=0.8,
        reg_alpha=0.1,
        reg_lambda=1.0,
        random_state=42,
        verbose=-1,
        n_jobs=-1,
    )
    model.fit(
        X_train, y_train,
        eval_set=[(X_val, y_val)],
        eval_metric="auc",
        callbacks=[lgb.early_stopping(stopping_rounds=50, verbose=False)],
    )
    print(f"  best_iteration: {model.best_iteration_}")

    # Eval
    proba_val  = model.predict_proba(X_val)[:, 1]
    proba_test = model.predict_proba(X_test)[:, 1]

    auc_val   = roc_auc_score(y_val,  proba_val)
    auc_test  = roc_auc_score(y_test, proba_test)
    ap_val    = average_precision_score(y_val,  proba_val)
    ap_test   = average_precision_score(y_test, proba_test)
    base_test = float(y_test.mean())

    print(f"\n  [VAL]  AUC={auc_val:.4f}  AvgPrec={ap_val:.4f}  base_rate={y_val.mean():.4%}")
    print(f"  [TEST] AUC={auc_test:.4f}  AvgPrec={ap_test:.4f}  base_rate={base_test:.4%}")
    print(f"  TEST lift over random: {ap_test / base_test:.2f}x")

    print("\n  --- TEST: FPR @ target Recall (maker defense lens) ---")
    print(f"  {'Target Recall':>14s}  {'Achieved':>10s}  {'FPR':>8s}  {'Threshold':>10s}  {'%selected':>10s}")
    print(f"  {'-'*14}  {'-'*10}  {'-'*8}  {'-'*10}  {'-'*10}")
    fpr_table = fpr_at_recall(y_test, proba_test, target_recalls=(0.80, 0.90, 0.95, 0.98, 0.99))
    for row in fpr_table:
        sel_pct = float((proba_test >= row["threshold"]).mean())
        print(f"  {row['target_recall']:>14.2%}  {row['achieved_recall']:>10.4f}  "
              f"{row['fpr']:>8.4f}  {row['threshold']:>10.4f}  {sel_pct:>10.2%}")

    print("\n  --- TEST: Recall @ target FPR ---")
    print(f"  {'Target FPR':>10s}  {'Achieved':>10s}  {'Recall':>8s}  {'Threshold':>10s}  {'%selected':>10s}")
    print(f"  {'-'*10}  {'-'*10}  {'-'*8}  {'-'*10}  {'-'*10}")
    rec_table = recall_at_fpr(y_test, proba_test, target_fprs=(0.05, 0.10, 0.15, 0.20, 0.30))
    for row in rec_table:
        sel_pct = float((proba_test >= row["threshold"]).mean())
        print(f"  {row['target_fpr']:>10.2%}  {row['achieved_fpr']:>10.4f}  "
              f"{row['recall']:>8.4f}  {row['threshold']:>10.4f}  {sel_pct:>10.2%}")

    # Top features
    print("\n  --- Top 10 features ---")
    imp = sorted(zip(ALL_FEATURES, model.feature_importances_), key=lambda x: -x[1])[:10]
    total = float(model.feature_importances_.sum()) or 1.0
    for n, v in imp:
        print(f"    {v/total:.4f}  {n}")

    return {
        "target": name,
        "definition": f"|{target_cfg['move_col']}| >= {target_cfg['threshold']}",
        "pos_rate_test": base_test,
        "auc_val": float(auc_val),
        "auc_test": float(auc_test),
        "ap_val": float(ap_val),
        "ap_test": float(ap_test),
        "lift_over_random": float(ap_test / base_test),
        "fpr_at_recall": fpr_table,
        "recall_at_fpr": rec_table,
        "best_iter": int(model.best_iteration_ or 0),
        "feature_importance": {n: float(v/total) for n, v in zip(ALL_FEATURES, model.feature_importances_)},
    }, model


