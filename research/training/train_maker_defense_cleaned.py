# Recall @ FPR analysis (the key metric for maker defense)
# ---------------------------------------------------------------------------

def recall_at_fpr(y_true, y_score, target_fprs=(0.05, 0.10, 0.15, 0.20, 0.30)):
    """For each target FPR, find threshold and report achieved recall."""
    fpr, tpr, thresholds = roc_curve(y_true, y_score)
    out = []
    for target in target_fprs:
        # Find the highest threshold where fpr <= target
        idx = np.searchsorted(fpr, target, side="right") - 1
        idx = max(0, min(idx, len(thresholds) - 1))
        out.append({
            "target_fpr": target,
            "achieved_fpr": float(fpr[idx]),
            "recall": float(tpr[idx]),
            "threshold": float(thresholds[idx]),
        })
    return out


def fpr_at_recall(y_true, y_score, target_recalls=(0.90, 0.95, 0.98, 0.99)):
    """For each target recall, find threshold and report FPR."""
    fpr, tpr, thresholds = roc_curve(y_true, y_score)
    out = []
    for target in target_recalls:
        # Lowest threshold where recall >= target
        idx = np.searchsorted(tpr, target, side="left")
        idx = max(0, min(idx, len(thresholds) - 1))
        out.append({
            "target_recall": target,
            "achieved_recall": float(tpr[idx]),
            "fpr": float(fpr[idx]),
            "threshold": float(thresholds[idx]),
        })
    return out


