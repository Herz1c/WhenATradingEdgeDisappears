"""Maker-Defense Classifier (Model 8c): dramatic-move early-warning.

Use case: hybrid maker/taker bot. In MAKER state, resting limit orders get
filled at stale prices if the market suddenly jumps 0.10+ in 5 seconds.
The cost of one missed dramatic move (catastrophic adverse fill) far
exceeds the cost of many false alarms (briefly withdraw makers, lose
some fee rebate).

Asymmetric objective:
  - Recall on dramatic moves >= 0.95 (we MUST catch them)
  - FPR can be 10-30% (acceptable: pull makers, requote shortly)
  - Precision is secondary

Targets trained:
  A) big_move_010_5s:  |mid_move_5s|  >= 0.10  (primary maker defense)
  B) big_move_007_3s:  |mid_move_3s|  >= 0.07  (earlier warning, faster horizon)
  C) big_move_005_5s:  |mid_move_5s|  >= 0.05  (precursor signal, more data)

Class imbalance handled via:
  - scale_pos_weight tuned per target
  - threshold sweep with recall@FPR analysis
  - early stopping on val log-loss

Leakage guard: all `mid_move_*` future columns are EXCLUDED from features.
"""
